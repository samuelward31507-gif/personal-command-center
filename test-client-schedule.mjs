import assert from "node:assert/strict";
import { splitAppointments, agenda, googleCalendarUrl, onMyWayText, parseAmount } from "./lib/client-schedule.ts";
const now = Date.parse("2026-11-10T18:00:00Z"), h = 3600_000;
const iso = t => new Date(t).toISOString();
const A = (id, t, ev = "") => ({ id, starts_at: iso(t), thread_id: "t" + id, customer_name: "Tom Becker", customer_phone: "+17205550177", event_id: ev });
const { due, upcoming } = splitAppointments([A("1", now - 3 * h), A("2", now - 0.5 * h), A("3", now + 26 * h, "g3")], now);
assert.deepEqual(due.map(a => a.id), ["1"]);
assert.deepEqual(upcoming.map(a => a.id), ["2", "3"]);
const ev = (id, s, e, title = "Job") => ({ id, title, start: iso(s), end: iso(e), allDay: false, link: "" });
const days = agenda(upcoming, [ev("g3", now + 26 * h, now + 27 * h), ev("x", now + 2 * h, now + 4 * h, "Henderson install"), ev("old", now - 5 * h, now - 4 * h), ev("far", now + 9 * 86400_000, now + 9 * 86400_000 + h)], now);
const flat = days.flatMap(d => d.items.map(i => i.kind === "estimate" ? "E" + i.appt.id : "V" + i.event.id));
assert.deepEqual(flat, ["E2", "Vx", "E3"], "dedupes Cinder's own event, drops past and far events, sorts by time");
assert.equal(googleCalendarUrl("mike@ridgeline.com"), "https://calendar.google.com/calendar/r/week?authuser=mike%40ridgeline.com");
assert.equal(googleCalendarUrl(), "https://calendar.google.com/calendar/r/week");
assert.equal(onMyWayText("Tom Becker", "Mike Rowe", "Ridgeline Fence"), "Hi Tom, it's Mike with Ridgeline Fence. On my way now, see you in about 15 minutes.");
assert.equal(onMyWayText("(303) 555-0199", "", "Ridgeline Fence"), "Hi, it's Ridgeline Fence. On my way now, see you in about 15 minutes.");
assert.equal(parseAmount("$9,400"), 9400);
assert.equal(parseAmount("9.4k"), 9400);
assert.equal(parseAmount("1250.50"), 1250.5);
assert.equal(parseAmount("abc"), null);
assert.equal(parseAmount("0"), null);
console.log("client-schedule ok");
