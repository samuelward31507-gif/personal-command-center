import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const { buildProposal, planItems, fillAgreement, SCHEDULE_TIER1, SCHEDULE_TIER2 } = await import("./lib/agreement-template.ts");
const { markdownToHtml, printPage } = await import("./lib/print-doc.ts");
let n = 0; const ok = f => { f(); n++; };
const base = { company: "On The Fence Inc", ownerName: "Brian Kramer", date: "November 13, 2026", payLink: "https://buy.stripe.com/abc", senderName: "Samuel Ward", senderPhone: "(205) 837-0211", senderEmail: "s@x.com" };
const t2 = buildProposal({ ...base, tier: "tier2", setupFee: 1997, monthlyFee: 1497 });
const t1 = buildProposal({ ...base, tier: "tier1", setupFee: 997, monthlyFee: 697 });
ok(() => assert.match(t2, /\[Pay \$1,997 securely with Stripe\]\(https:\/\/buy\.stripe\.com\/abc\)/, "setup link on the proposal"));
ok(() => assert.match(t1, /\[Pay \$997 securely with Stripe\]/));
ok(() => assert.doesNotMatch(buildProposal({ ...base, payLink: undefined, tier: "tier1", setupFee: 997, monthlyFee: 697 }), /\]\(undefined\)/, "no broken link without one"));
ok(() => assert.match(t2, /Brian Kramer, On The Fence Inc/));
ok(() => assert.match(t2, /\$1,497/));
ok(() => assert.match(buildProposal({ ...base, tier: "tier2", setupFee: 1997, monthlyFee: 1497, addon: true }), /Reactivation/));
ok(() => assert.doesNotMatch(t1, /follow(ed)? up on days/i, "tier 1 has no quote follow-up"));
ok(() => assert.doesNotMatch(t1 + t2, /\bClient's\b|\bCinder app\b|\bapp\b/i, "plain wording, no app"));
ok(() => assert.doesNotMatch(SCHEDULE_TIER1 + SCHEDULE_TIER2, /Cinder app/i, "the app is not sold"));
for (const tier of ["tier1", "tier2"]) for (const it of planItems(tier)) ok(() => assert.ok(it.length < 140, it));
const html = markdownToHtml(t2);
ok(() => assert.match(html, /<a href="https:\/\/buy\.stripe\.com\/abc">Pay \$1,997 securely with Stripe<\/a>/));
ok(() => assert.match(html, /<table>/));
ok(() => assert.match(html, /<ol>/));
ok(() => assert.doesNotMatch(markdownToHtml("[x](javascript:alert(1)) <b>"), /href="javascript|<b>/, "no script links, html escaped"));
const page = printPage({ title: "P", kind: "Proposal", business: "Cinder Revenue Company", md: t2 });
ok(() => assert.doesNotMatch(page, /rgba\(18,20,23,\.32\)/, "body text is dark, not faded"));
ok(() => assert.match(fillAgreement({ tier: "tier2", date: "d", company: "X", ownerName: "Y", email: "", phone: "", location: "", setupFee: 1997, monthlyFee: 1497 }), /1,997/));
ok(() => assert.doesNotMatch(readFileSync("app/api/proposals/route.ts", "utf8"), /api\.anthropic\.com/, "proposal is a template, not an AI draft"));
console.log(`Proposal checks passed (${n} assertions).`);
ok(() => assert.match(readFileSync("lib/client-runtime-run.ts", "utf8"), /firstBookingBilling\(sql, c\)/, "the first booking reminds Sam to start the monthly"));
console.log("First-booking billing check passed.");
