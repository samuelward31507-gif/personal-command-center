# One hairline drawing per page, each made for that page and used nowhere else.
# Canvas is 560 x 320. Every drawing has a list of steps (drawn in order as the visitor scrolls)
# and one plain rectangle, the focal, that fills and grows into the next screen.
import math


def P(d, c=''):
    return ('s ' + c, '<path pathLength="1" d="%s"/>' % d)


def L(x1, y1, x2, y2, c=''):
    return P('M%g %g L%g %g' % (x1, y1, x2, y2), c)


def R(x, y, w, h, r=0, c=''):
    return ('s ' + c, '<rect pathLength="1" x="%g" y="%g" width="%g" height="%g" rx="%g"/>' % (x, y, w, h, r))


def C(cx, cy, r, c=''):
    return ('s ' + c, '<circle pathLength="1" cx="%g" cy="%g" r="%g"/>' % (cx, cy, r))


def DA(d):          # a dashed guide: fades in rather than draws
    return ('da', '<path d="%s"/>' % d)


def N(x, y, s=6):   # a small filled node
    return ('nd', '<rect x="%g" y="%g" width="%g" height="%g"/>' % (x - s / 2, y - s / 2, s, s))


def head(x, y, d=1):     # arrow head pointing right (d=1) or left (d=-1)
    return P('M%g %g l%g 6 l%g 6' % (x - 8 * d, y - 6, 8 * d, -8 * d))


def star(cx, cy, r, c=''):
    pts = []
    for k in range(10):
        a = -math.pi / 2 + k * math.pi / 5; rr = r if k % 2 == 0 else r * .42
        pts.append('%.1f %.1f' % (cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return P('M' + ' L'.join(pts) + 'Z', c)


def person(cx, cy, c=''):
    return [C(cx, cy - 8, 6, c), P('M%g %g a11 11 0 0 1 22 0' % (cx - 11, cy + 12), c)]


def env(x, y, w, h, c=''):
    return [R(x, y, w, h, 3, c), P('M%g %g l%g %g l%g %g' % (x, y, w / 2, h * .46, w / 2, -h * .46), c)]


def house(x, y, w, h, c=''):
    return [R(x, y, w, h, 0, c), P('M%g %g L%g %g L%g %g' % (x - 6, y, x + w / 2, y - h * .62, x + w + 6, y), c)]


def _flat(x):
    return x if isinstance(x, list) else [x]


