import assert from "node:assert/strict";
process.env.CINDER_TOKEN_KEY = "x".repeat(40);
const { encryptToken, decryptToken, buildRaw, complianceFooter, emailFromIdToken, isEmail } = await import("./lib/gmail.ts");
let n = 0; const ok = f => { f(); n++; };
const enc = encryptToken("1//refresh-token");
ok(() => assert.notEqual(enc, "1//refresh-token"));
ok(() => assert.equal(decryptToken(enc), "1//refresh-token", "round trip"));
ok(() => assert.notEqual(encryptToken("a"), encryptToken("a"), "fresh IV each time"));
const parts = enc.split("."), body = Buffer.from(parts[2], "base64url"); body[0] ^= 1;
ok(() => assert.throws(() => decryptToken([parts[0], parts[1], body.toString("base64url")].join(".")), "tampering is caught"));
const raw = Buffer.from(buildRaw({ from: "sam@cinderrevenue.com", fromName: "Sam at Cinder", to: "a@b.com", subject: "Héllo\r\nBcc: evil@x.com", body: "Hi\nthere", inReplyTo: "<m1@mail.gmail.com>" }), "base64url").toString("utf8");
ok(() => assert.match(raw, /^From: Sam at Cinder <sam@cinderrevenue\.com>\r\nTo: <a@b\.com>\r\n/));
ok(() => assert.doesNotMatch(raw, /\r\nBcc:/, "header injection is flattened"));
ok(() => assert.match(raw, /Subject: =\?UTF-8\?B\?/, "non-ASCII subjects are encoded"));
ok(() => assert.match(raw, /In-Reply-To: <m1@mail\.gmail\.com>/));
ok(() => assert.equal(Buffer.from(raw.split("\r\n\r\n")[1].replace(/\r\n/g, ""), "base64").toString("utf8"), "Hi\r\nthere"));
ok(() => assert.match(complianceFooter("Cinder Revenue Company", "PO Box 1, Denver CO"), /PO Box 1, Denver CO\nNot interested\? Reply "unsubscribe"/));
const tok = "h." + Buffer.from(JSON.stringify({ email: "Sam@CinderRevenue.com" })).toString("base64url") + ".s";
ok(() => assert.equal(emailFromIdToken(tok), "sam@cinderrevenue.com"));
ok(() => assert.equal(isEmail("a@b.co"), true)); ok(() => assert.equal(isEmail("a@b"), false));
console.log(`Gmail checks passed (${n} assertions).`);
