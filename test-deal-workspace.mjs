// Regression tests for discovery + proposals. Run with: node --experimental-strip-types test-deal-workspace.mjs
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { cleanDiscovery, discoveryCompleteness, stageForProposal, buildProposalPrompt, DISCOVERY_FIELDS, stageForContract, buildAgreementPrompt, buildEmailPrompt, parseEmailDraft, mailtoLink, isEmailPurpose, EMAIL_PURPOSES } from "./lib/deal-workspace.ts";

let n = 0;
const ok = fn => { fn(); n++; };
ok(() => assert.deepEqual(cleanDiscovery({ pain: "  missed calls  ", hacker: "x", monthlyLeads: 5 }), { pain: "missed calls" }, "unknown keys and non-strings dropped"));
ok(() => assert.equal(cleanDiscovery({ pain: "x".repeat(5000) }).pain.length, 2000));
ok(() => assert.equal(discoveryCompleteness({}), 0));
ok(() => assert.equal(discoveryCompleteness({ decisionMaker: "a", leadSources: "b", monthlyLeads: "c", avgJobValue: "d", responseTime: "e", pain: "f", timeline: "g" }), 100));
ok(() => assert.equal(stageForProposal("sent", "meeting_held"), "proposal"));
ok(() => assert.equal(stageForProposal("sent", "proposal"), null));
ok(() => assert.equal(stageForProposal("accepted", "proposal"), null, "accepted is not won — the agreement still has to be signed"));
ok(() => assert.equal(stageForProposal("accepted", "meeting_held"), "proposal"));
ok(() => assert.equal(stageForProposal("declined", "proposal"), "lost"));
ok(() => assert.equal(stageForProposal("accepted", "won"), null, "closed deals are never moved"));
ok(() => assert.equal(stageForProposal("sent", "lost"), null));
const pr = buildProposalPrompt({ company: "Dive Deep Custom Pools", contactName: "", location: "DFW", offerLabel: "Tier 2", setupFee: 3000, monthlyFee: 1500, discovery: { pain: "leads go cold" }, auditSummary: "", notes: "" });
ok(() => assert.match(pr.system, /Never invent statistics/));
ok(() => assert.match(pr.system, /guarantees/));
ok(() => assert.match(pr.user, /\$3,000 setup \+ \$1,500\/month/));
ok(() => assert.match(pr.user, /Biggest pain, in their words: leads go cold/));
ok(() => assert.ok(DISCOVERY_FIELDS.length >= 10));
// agreements
ok(() => assert.equal(stageForContract("signed", "proposal"), "won"));
ok(() => assert.equal(stageForContract("sent", "proposal"), null));
ok(() => assert.equal(stageForContract("signed", "lost"), null, "closed deals are never moved"));
ok(() => assert.equal(stageForContract("signed", "won"), null));
const ag = buildAgreementPrompt({ providerName: "", company: "Ridgeline Fence", contactName: "Mike R.", location: "Denver", offerLabel: "Tier 1", setupFee: 1500, monthlyFee: 997, proposal: "## Investment\n$1,500 setup", today: "October 29, 2026" });
ok(() => assert.match(ag.user, /Provider: \[Your legal business name\]/, "unknown legal name stays a blank, never guessed"));
ok(() => assert.match(ag.system, /No guarantees of results/));
ok(() => assert.match(ag.system, /\[bracketed blank\]/));
ok(() => assert.match(ag.user, /\$1,500 setup \+ \$997\/month/));
ok(() => assert.match(buildAgreementPrompt({ providerName: "CGC LLC", company: "X", contactName: "", location: "", offerLabel: "T", setupFee: 1, monthlyFee: 1, proposal: "p", today: "t" }).user, /Provider: CGC LLC/));
// follow-up emails
ok(() => assert.ok(isEmailPurpose("proposal_follow_up") && !isEmailPurpose("sms") && !isEmailPurpose("toString")));
ok(() => assert.ok(Object.keys(EMAIL_PURPOSES).every(k => !/sms|text message/i.test(EMAIL_PURPOSES[k].label + EMAIL_PURPOSES[k].brief)), "email only"));
const em = buildEmailPrompt({ purpose: "no_show", company: "Ironwood", firstName: "Dale", senderName: "Samuel", stage: "meeting_booked", discovery: { pain: "slow replies" }, nextStep: "", proposalSentAt: null, notes: "" });
ok(() => assert.match(em.system, /Email only/));
ok(() => assert.match(em.system, /never invent/));
ok(() => assert.match(em.user, /To: Dale at Ironwood/));
ok(() => assert.deepEqual(parseEmailDraft("Subject: Quick follow-up\n\nHi Dale,\nThanks."), { subject: "Quick follow-up", body: "Hi Dale,\nThanks." }));
ok(() => assert.deepEqual(parseEmailDraft("**Subject:** Hi\nBody"), { subject: "Hi", body: "Body" }));
ok(() => assert.deepEqual(parseEmailDraft("Just a body"), { subject: "", body: "Just a body" }));
ok(() => assert.equal(mailtoLink("dale@ironwood.com", "Hi there", "a&b\nc"), "mailto:dale@ironwood.com?subject=Hi%20there&body=a%26b%0Ac"));
ok(() => assert.equal(mailtoLink("not an email?bcc=x@y.com", "s", "b"), "mailto:?subject=s&body=b", "bad addresses are dropped, no header injection"));
const api = readFileSync("app/api/deal-workspace/route.ts", "utf8") + readFileSync("app/api/proposals/route.ts", "utf8") + readFileSync("app/api/agreements/route.ts", "utf8") + readFileSync("app/api/follow-up-email/route.ts", "utf8");
ok(() => assert.doesNotMatch(readFileSync("app/api/follow-up-email/route.ts", "utf8"), /twilio|resend|sendgrid|nodemailer|fetch\("https:\/\/(?!api\.anthropic)/i, "drafts only — nothing is sent"));
ok(() => assert.doesNotMatch(api, /status\s*=\s*'paid'|DELETE FROM/i, "never marks paid, never deletes"));
ok(() => assert.ok((api.match(/owner_id = \$\{user\.id\}/g) || []).length >= 10, "owner-scoped"));
ok(() => assert.match(api, /if \(!user\) return fail\("Unauthorized", 401\)/));
ok(() => assert.match(api, /runDealHandoff/, "won runs the onboarding handoff"));
const page = readFileSync("app/crm/deals/[id]/page.tsx", "utf8");
ok(() => assert.match(page, /confirm\("Mark accepted\?/, "accepted asks first"));
ok(() => assert.match(page, /confirm\("Mark the agreement signed\?/, "signed asks first"));
ok(() => assert.match(page, /not legal advice/));
ok(() => assert.doesNotMatch(page, /sendEmail|resend|twilio|sms/i, "never sends anything"));
console.log(`Deal workspace regression checks passed (${n} assertions).`);
