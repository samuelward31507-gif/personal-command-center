import assert from "node:assert/strict";
process.env.CINDER_TOKEN_KEY = "test-key-0123456789abcdef";
const A = await import("./lib/client-app.ts");
const t = A.makeSession(["11111111-1111-1111-1111-111111111111"], "7205550148", 1000);
const s = A.readSession(t, 2000);
assert.deepEqual(s.projects, ["11111111-1111-1111-1111-111111111111"]); assert.equal(s.phone, "7205550148");
assert.equal(A.readSession(t, 1000 + 91 * 86400000), null, "expires after 90 days");
assert.equal(A.readSession(t.slice(0, -2) + "xx", 2000), null, "tampered signature");
const [body, sig] = t.split(".");
const forged = Buffer.from(JSON.stringify({ projects: ["22222222-2222-2222-2222-222222222222"], phone: "1", exp: 9e15 })).toString("base64url");
assert.equal(A.readSession(`${forged}.${sig}`, 2000), null, "forged body");
assert.equal(A.readSession(undefined), null); assert.equal(A.readSession("junk"), null);
assert.equal(A.cookieFrom(`a=1; ${A.APP_COOKIE}=${encodeURIComponent(t)}; b=2`), t);
assert.equal(A.cookieFrom("a=1"), null);
assert.match(A.sessionCookie(t), /HttpOnly; SameSite=Lax; Secure/);
assert.equal(A.phone10("+1 (720) 555-0148"), "7205550148");
const c = A.newCode(); assert.match(c, /^\d{6}$/);
assert.equal(A.hashCode("720-555-0148", "123456"), A.hashCode("+17205550148", " 123456"));
assert.notEqual(A.hashCode("7205550148", "123456"), A.hashCode("7205550148", "123457"));
console.log("client app ok");
